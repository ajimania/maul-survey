const {id} = await api('admin.project.save', {project});
const {project: saved} = await api('admin.project.get', {id});
for (const [n, person] of people.entries()) {
  const start = await api('iv.start', {p: saved.openToken, consent: true, mode: 'voice'});
  const t = start.token;
  const turns = [];
  const ack = ['네, 말씀 잘 들었습니다.', '그러셨군요.', '네, 알겠습니다.', '말씀 고맙습니다.'];
  project.questions.forEach((q, i) => {
    turns.push(['ai', i === 0 ? `안녕하세요. 저는 ○○구 평생학습관의 인터뷰를 도와드리는 AI 진행자입니다. 10분쯤 걸리고 정답은 없으니 편하게 말씀해 주세요. ${q.text}` : `${ack[(n + i) % ack.length]} ${q.text}`]);
    turns.push(['p', person.a[i]]);
    for (const [fq, fa] of person.f?.[i + 1] || []) { turns.push(['ai', fq]); turns.push(['p', fa]); }
  });
  turns.push(['ai', '마지막으로 더 하고 싶은 말씀이 있으세요?'], ['p', person.end], ['ai', '말씀 감사합니다. 들려주신 이야기는 잘 전하겠습니다.']);
  let sec = 0;
  for (const [seq, [role, text]] of turns.entries()) {
    sec += role === 'ai' ? 9 : 14 + Math.round(text.length * 0.45);
    await api('iv.turn', {t, seq, role, text, sec});
  }
  await api('iv.finish', {t, reason: 'done', sec});
  if (n < 7) await api('admin.review', {token: t, verdict: 'include', note: '', by: project.researcher});   // 마지막 한 건은 검증 대기로 남겨 둔다
  console.log(`참여자 ${n + 1}: 발화 ${turns.length}개, ${Math.round(sec / 60)}분`);
}
