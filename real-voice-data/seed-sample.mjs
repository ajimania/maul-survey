const BASE = process.env.BASE || 'http://localhost:4192';
const PASS = process.env.PASS || 'dev';

async function api(action, body = {}) {
  const r = await fetch(`${BASE}/api/real-voice`, {method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify({action, pass: PASS, mock: true, ...body})});
  const j = await r.json();
  if (!r.ok) throw new Error(`${action}: ${j.message}`);
  return j;
}

